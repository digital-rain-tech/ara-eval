/**
 * Build-time codegen: bundle the shared scenarios/ and prompts/ data (which live
 * at the repo root, OUTSIDE web/) into a TypeScript module that gets compiled
 * into the app.
 *
 * Why: the web app reads these files at request time via fs. That works locally
 * (the repo is on disk) but breaks on Vercel, where the serverless function
 * bundle only contains the web/ project and Next's tracer won't follow
 * dynamically-named fs reads. Importing a generated module guarantees the data
 * is bundled. Runs on predev/prebuild/pretest (see package.json).
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..", "..");
const scenariosDir = path.join(repoRoot, "scenarios");
const promptsDir = path.join(repoRoot, "prompts");
const outFile = path.join(__dirname, "..", "src", "generated", "shared-data.ts");

/** Read every *.json scenario set, keyed by filename. */
function readScenarioSets() {
  const sets = {};
  for (const f of fs.readdirSync(scenariosDir)) {
    if (!f.endsWith(".json")) continue;
    sets[f] = JSON.parse(fs.readFileSync(path.join(scenariosDir, f), "utf-8"));
  }
  return sets;
}

/** Recursively read every prompt file, keyed by its posix path relative to prompts/. */
function readPromptFiles(dir = promptsDir, acc = {}) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      readPromptFiles(full, acc);
    } else {
      const rel = path.relative(promptsDir, full).split(path.sep).join("/");
      acc[rel] = fs.readFileSync(full, "utf-8");
    }
  }
  return acc;
}

const scenarioSets = readScenarioSets();
const promptFiles = readPromptFiles();

const banner =
  "// AUTO-GENERATED by scripts/generate-shared-data.mjs — DO NOT EDIT.\n" +
  "// Source: ../scenarios/*.json and ../prompts/**. Regenerated on predev/prebuild/pretest.\n\n";

const body =
  `export const SCENARIO_SETS: Record<string, unknown[]> = ${JSON.stringify(scenarioSets)};\n\n` +
  `export const PROMPT_FILES: Record<string, string> = ${JSON.stringify(promptFiles)};\n`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, banner + body);

console.log(
  `[generate-shared-data] ${Object.keys(scenarioSets).length} scenario sets, ` +
    `${Object.keys(promptFiles).length} prompt files -> src/generated/shared-data.ts`,
);
